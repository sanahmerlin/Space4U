import 'package:flutter/material.dart';
import 'package:provider/provider.dart';
import 'package:firebase_core/firebase_core.dart';
import 'core/app_theme.dart';
import 'presentation/wrapper/auth_wrapper.dart';
import 'providers/parking_provider.dart';
import 'firebase_options.dart'; // generated by flutterfire

void main() async {
  WidgetsFlutterBinding.ensureInitialized();
  try {
     // Assuming default initialization works or user will configure
    await Firebase.initializeApp(
       // options: DefaultFirebaseOptions.currentPlatform, // Uncomment if generated
    );
  } catch (e) {
    debugPrint('Firebase initialization failed: $e');
  }

  runApp(
    MultiProvider(
      providers: [
        ChangeNotifierProvider(create: (_) => ParkingProvider()),
      ],
      child: const Space4UApp(),
    ),
  );
}

class Space4UApp extends StatelessWidget {
  const Space4UApp({Key? key}) : super(key: key);

  @override
  Widget build(BuildContext context) {
    return MaterialApp(
      title: 'Space4U',
      debugShowCheckedModeBanner: false,
      theme: AppTheme.darkTheme,
      home: const AuthWrapper(),
    );
  }
}
